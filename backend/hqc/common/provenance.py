"""Data provenance: checksums and the tracked ``data/MANIFEST.yaml``.

The manifest records, for every downloaded (RAW) or generated (PROCESSED/DERIVED)
artifact: source, version, retrieval/processing time, SHA-256, size, license and
local path. Entries are upserted by ``artifact_id`` and written in a stable order.
"""

from __future__ import annotations

import hashlib
from enum import StrEnum
from pathlib import Path

import yaml
from pydantic import Field, ValidationError

from hqc.common.errors import MalformedSourceDataError
from hqc.common.schemas.base import HQCModel, NonEmptyStr, UTCDatetime

MANIFEST_SCHEMA_VERSION = 1
_CHUNK = 1 << 20
SHA256_PATTERN = r"^[0-9a-f]{64}$"


def sha256_bytes(data: bytes) -> str:
    """Hex SHA-256 of a byte string."""
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    """Hex SHA-256 of a file, streamed."""
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while chunk := handle.read(_CHUNK):
            digest.update(chunk)
    return digest.hexdigest()


class ArtifactKind(StrEnum):
    RAW = "RAW"  # observed source data, byte-for-byte as downloaded
    PROCESSED = "PROCESSED"  # deterministic normalisation of RAW data
    DERIVED = "DERIVED"  # modelling artifact built from processed data (e.g. vocabulary)


class ManifestFile(HQCModel):
    """One file inside a multi-file artifact (e.g. one Attack Flow document)."""

    name: NonEmptyStr
    source_url: str | None = None
    sha256: str = Field(pattern=SHA256_PATTERN)
    size_bytes: int = Field(ge=0)


class ManifestArtifact(HQCModel):
    artifact_id: NonEmptyStr
    kind: ArtifactKind
    description: NonEmptyStr
    version: NonEmptyStr
    local_path: NonEmptyStr = Field(description="Path relative to the project root.")
    sha256: str | None = Field(default=None, pattern=SHA256_PATTERN)
    size_bytes: int | None = Field(default=None, ge=0)
    source_url: str | None = None
    upstream_ref: str | None = Field(default=None, description="Upstream commit/tag/release.")
    release_modified: str | None = None
    retrieved_at: UTCDatetime | None = None
    processed_at: UTCDatetime | None = None
    processing_version: str | None = None
    inputs: list[str] = Field(default_factory=list, description="artifact_ids used as input")
    license: str | None = None
    license_url: str | None = None
    files: list[ManifestFile] = Field(default_factory=list)
    notes: str | None = None


class Manifest(HQCModel):
    schema_version: int = MANIFEST_SCHEMA_VERSION
    artifacts: list[ManifestArtifact] = Field(default_factory=list)

    def get(self, artifact_id: str) -> ManifestArtifact | None:
        return next((a for a in self.artifacts if a.artifact_id == artifact_id), None)

    def upsert(self, artifact: ManifestArtifact) -> None:
        """Insert or replace an artifact; keeps artifacts sorted by id."""
        kept = [a for a in self.artifacts if a.artifact_id != artifact.artifact_id]
        self.artifacts = sorted([*kept, artifact], key=lambda a: a.artifact_id)


def load_manifest(path: Path) -> Manifest:
    """Load the manifest, or return an empty one if the file does not exist."""
    if not path.exists():
        return Manifest()
    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        return Manifest.model_validate(raw)
    except (yaml.YAMLError, ValidationError) as exc:
        raise MalformedSourceDataError(f"Invalid manifest {path}: {exc}") from exc


def save_manifest(manifest: Manifest, path: Path) -> None:
    """Write the manifest as YAML with a header comment."""
    header = (
        "# Data manifest (tracked). Generated by scripts/ - do not edit by hand.\n"
        "# RAW = observed source data; PROCESSED/DERIVED = generated from RAW.\n"
    )
    body = yaml.safe_dump(
        manifest.model_dump(mode="json", exclude_none=True), sort_keys=False, allow_unicode=True
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + body, encoding="utf-8")
